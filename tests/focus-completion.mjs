import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const c=vm.createContext({});
vm.runInContext(fs.readFileSync('public/focus-model.js','utf8'),c);
const m=c.MinimalFocus,day=d=>d.toISOString().slice(0,10),deadline=Date.parse('2026-10-18T23:59:00Z');
const timer=()=>({id:'one',phase:'focus',status:'running',seconds:60,remaining:60,deadline,topic:'Read',method:'Reading'});
let s={focusTimer:timer(),focusSessions:[],learning:[]};
assert.equal(m.finish(s,'one',deadline-1,day),null);
assert.equal(m.finish(s,'wrong',deadline,day),null);
s.focusTimer.status='paused';s.focusTimer.remaining=20;
assert.equal(m.finish(s,'one',deadline+90000,day),null);
s.focusTimer.status='running';s.focusTimer.deadline=deadline+90000;
assert.equal(m.remaining(s.focusTimer,deadline+89500),1);
assert.equal(m.finish(s,'one',deadline+89999,day),null);
let r=m.finish(s,'one',deadline+150000,day);
assert.ok(r.added&&r.firstLearningDay);
assert.equal(s.focusSessions[0].date,'2026-10-19');
assert.equal(s.focusSessions.length,1);assert.equal(s.learning.length,1);
assert.equal(m.finish(s,'one',deadline+150001,day),null);
s.focusTimer={...timer(),status:'review',remaining:0};
r=m.finish(s,'one',deadline+150000,day);
assert.equal(r.added,false);assert.equal(s.focusSessions.length,1);assert.equal(s.learning.length,1);
s.focusTimer={...timer(),id:'two',status:'paused',remaining:0,deadline:deadline+90000};
r=m.finish(s,'two',deadline+150000,day);
assert.equal(r.firstLearningDay,false);assert.equal(s.learning.length,2);
s.focusTimer={...timer(),id:'break',phase:'break'};
assert.equal(m.finish(s,'break',deadline+150000,day),null);
console.log('PASS: early/pause protection, resumed deadlines, automatic late completion, correct completion day, legacy zero timers, replay deduplication, daily reward eligibility and no break credit.');
